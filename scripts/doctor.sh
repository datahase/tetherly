#!/usr/bin/env bash
# Read-only toolchain check against the versions pinned in docs/PLAN.md. Installs nothing.
set -uo pipefail
cd "$(dirname "$0")/.."
fail=0
check() { if eval "$2" >/dev/null 2>&1; then echo "ok   $1"; else echo "FAIL $1"; fail=1; fi; }

check "Xcode 27 (xcodebuild -version)"            '[[ "$(xcodebuild -version | head -1)" == "Xcode 27."* ]]'
check "JDK 17+ (java -version)"                   '[[ "$(java -version 2>&1 | head -1 | sed -E "s/.*\"([0-9]+).*/\1/")" -ge 17 ]]'
check "Android SDK platform 36 (ANDROID_HOME)"    '[[ -d "${ANDROID_HOME:-$HOME/Library/Android/sdk}/platforms/android-36" ]]'
# Official Gradle wrapper jar checksum (https://services.gradle.org/distributions/gradle-9.3.1-wrapper.jar.sha256);
# the jar was generated by Gradle 9.3.1 and is compatible with the 9.8.1 distribution it downloads.
check "gradle-wrapper.jar SHA-256"                '[[ "$(shasum -a 256 apps/android/gradle/wrapper/gradle-wrapper.jar | cut -d" " -f1)" == b3a875ddc1f044746e1b1a55f645584505f4a10438c1afea9f15e92a7c42ec13 ]]'
check "Gradle distribution SHA-256 pinned"        'grep -q "^distributionSha256Sum=dce76f55f8e251a3a1f130eb120f30b3d271de2b76c9b0729d316b5a1b6dc01f$" apps/android/gradle/wrapper/gradle-wrapper.properties'
if [[ -f apps/macos/Signing.local.xcconfig ]]; then
  team=$(sed -n 's/^DEVELOPMENT_TEAM *= *//p' apps/macos/Signing.local.xcconfig)
  check "Signing identity for team $team"  'security find-identity -v -p codesigning | grep -q "($team)"'
else
  echo "info Mac host builds ad hoc (no apps/macos/Signing.local.xcconfig)"
fi
echo "info adb: $(adb devices -l 2>/dev/null | awk '$2=="device" && $1 !~ /^emulator-/' | wc -l | tr -d " ") physical device(s), $(adb devices 2>/dev/null | grep -c "^emulator-") emulator(s)"
exit $fail
